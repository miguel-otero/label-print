    def get_batch_history(self) -> list[PrintBatchHistory]:
        self._require_postgres()
        with self._connect() as conn:
            batches = conn.execute(
                """
                select id, timestamp, "user", format, warehouse, requested_labels,
                       printed_labels, failed_labels, status, message,
                       source, source_document, source_date
                from print_batches
                order by timestamp desc
                limit 200
                """
            ).fetchall()
            if not batches:
                return []

            batch_ids = [row["id"] for row in batches]
            item_rows = conn.execute(
                """
                select batch_id, product_id, reference, product_description, barcode,
                       presentation, inventory_quantity, requested_labels,
                       printed_labels, failed_labels, status, message
                from print_batch_items
                where batch_id = any(%s)
                order by id
                """,
                (batch_ids,),
            ).fetchall()

        grouped: dict[int, list[InventoryBatchItemResult]] = defaultdict(list)
        for row in item_rows:
            grouped[int(row["batch_id"])].append(
                InventoryBatchItemResult(
                    product_id=row["product_id"],
                    reference=row["reference"],
                    description=row["product_description"],
                    barcode=row["barcode"],
                    presentation=row["presentation"],
                    inventory_quantity=row["inventory_quantity"],
                    requested_labels=row["requested_labels"],
                    printed_labels=row["printed_labels"],
                    failed_labels=row["failed_labels"],
                    status=row["status"],
                    message=row["message"],
                )
            )
        return [
            PrintBatchHistory(
                **row,
                items=grouped[int(row["id"])],
            )
            for row in batches
        ]

    def _inventory_item_from_row(self, row: dict) -> InventoryItem:
        presentations: list[Product] = []
        for item in row["presentations"]:
            try:
                product = Product.model_validate(item)
                self._validate_presentation(product)
            except (ValueError, InventoryPrintError):
                continue
            presentations.append(product)

        inventory_quantity = Decimal(row["inventory_quantity"])
        if inventory_quantity <= 0:
            reason = "La existencia no es positiva."
        elif not presentations:
            reason = "No tiene una presentacion valida en productos."
        else:
            reason = None

        return InventoryItem(
            id=row["id"],
            warehouse=row["warehouse"],
            reference=row["reference"],
            inventory_quantity=inventory_quantity,
            presentations=presentations,
            printable=reason is None,
            unavailable_reason=reason,
        )


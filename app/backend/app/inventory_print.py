    def print_batch(
        self,
        payload: InventoryBatchPrintRequest,
        *,
        user: str,
    ) -> InventoryBatchPrintResponse:
        self._require_postgres()
        configured_limit = self.get_settings().max_labels_per_batch
        requested_labels = sum(item.quantity for item in payload.items)
        if requested_labels > configured_limit:
            raise InventoryPrintError(
                f"El lote solicita {requested_labels} etiquetas y el limite configurado es {configured_limit}."
            )

        inventory_table = sql.Identifier(self.settings.inventory_table)
        products_table = sql.Identifier(self.settings.products_table)
        formats_table = sql.Identifier(self.settings.formats_table)

        validated: list[tuple[InventoryBatchItemResult, Product]] = []
        seen_inventory_ids: set[int] = set()
        with self._connect() as conn:
            format_row = conn.execute(
                sql.SQL(
                    """
                    select id, name, code, width_mm, height_mm, preview_type, active, template_file
                    from {}
                    where code = %s and active = true
                    """
                ).format(formats_table),
                (payload.format,),
            ).fetchone()
            if format_row is None:
                raise InventoryPrintError("El formato seleccionado no existe o esta inactivo.")
            label_format = LabelFormat.model_validate(format_row)

            for item in payload.items:
                if item.quantity <= 0:
                    continue
                if item.inventory_id in seen_inventory_ids:
                    raise InventoryPrintError("Un articulo de inventario aparece repetido en el lote.")
                seen_inventory_ids.add(item.inventory_id)

                row = conn.execute(
                    sql.SQL(
                        """
                        select inv.id_inventory,
                               inv.bodega,
                               inv.referencia,
                               inv.inventario,
                               p.id,
                               p.linea as line,
                               p.referencia as product_code,
                               p.descripcion as description,
                               p.um_siesa as unit_of_measure,
                               p.codigo_barra as barcode,
                               p.unidad_de_medida_barras as barcode_unit_measure,
                               p.cantidadxum as quantity_per_unit,
                               p.codigo_propio as own_code,
                               concat_ws(
                                   ' ',
                                   nullif(p.cantidadxum, ''),
                                   nullif(p.unidad_de_medida_barras, '')
                               ) as presentation_quantity
                        from {inventory} as inv
                        inner join {products} as p
                          on p.id = %(product_id)s
                         and p.referencia = inv.referencia
                         and p.codigo_propio = true
                        where inv.id_inventory = %(inventory_id)s
                        """
                    ).format(inventory=inventory_table, products=products_table),
                    {
                        "inventory_id": item.inventory_id,
                        "product_id": item.product_id,
                    },
                ).fetchone()
                if row is None:
                    raise InventoryPrintError(
                        f"El articulo {item.inventory_id} o su presentacion ya no estan disponibles."
                    )
                if row["bodega"] != payload.warehouse:
                    raise InventoryPrintError(
                        f"El articulo {row['referencia']} no pertenece a la bodega seleccionada."
                    )

                product = Product.model_validate(row)
                self._validate_presentation(product)
                validated.append(
                    (
                        InventoryBatchItemResult(
                            product_id=product.id,
                            reference=str(row["referencia"]),
                            description=product.description,
                            barcode=product.barcode,
                            presentation=product.presentation_quantity,
                            inventory_quantity=row["inventario"],
                            requested_labels=item.quantity,
                            printed_labels=0,
                            failed_labels=0,
                            status="error",
                        ),
                        product,
                    )
                )

        labels = [
            BatchLabel(item_key=index, product=product)
            for index, (result, product) in enumerate(validated)
            for _ in range(result.requested_labels)
        ]
        if not labels:
            raise InventoryPrintError("El lote no tiene etiquetas para imprimir.")
        requested_labels = len(labels)
        outcomes = self.printer.print_batch(label_format=label_format, labels=labels)

        results: list[InventoryBatchItemResult] = []
        for index, (result, _) in enumerate(validated):
            outcome = outcomes[index]
            if outcome.failed_labels == 0:
                status = "success"
            elif outcome.printed_labels == 0:
                status = "error"
            else:
                status = "partial"
            results.append(
                result.model_copy(
                    update={
                        "printed_labels": outcome.printed_labels,
                        "failed_labels": outcome.failed_labels,
                        "status": status,
                        "message": "; ".join(outcome.errors) or None,
                    }
                )
            )

        printed_labels = sum(item.printed_labels for item in results)
        failed_labels = sum(item.failed_labels for item in results)
        if failed_labels == 0:
            batch_status = "success"
            message = None
        elif printed_labels == 0:
            batch_status = "error"
            message = "No se pudo imprimir ninguna etiqueta del lote."
        else:
            batch_status = "partial"
            message = (
                f"Se imprimieron {printed_labels} etiquetas y {failed_labels} presentaron error."
            )

        batch_id = self._save_batch_history(
            user=user,
            format_code=label_format.code,
            warehouse=payload.warehouse,
            requested_labels=requested_labels,
            printed_labels=printed_labels,
            failed_labels=failed_labels,
            status=batch_status,
            message=message,
            items=results,
        )
        return InventoryBatchPrintResponse(
            batch_id=batch_id,
            status=batch_status,
            requested_labels=requested_labels,
            printed_labels=printed_labels,
            failed_labels=failed_labels,
            message=message,
            items=results,
        )


DEFAULT_MAX_LABELS_PER_BATCH = 400


class InventoryPrintError(RuntimeError):
    pass


class InventoryPrintService:
    def __init__(self, settings: Settings, printer: Printer) -> None:
        self.settings = settings
        self.printer = printer

    def _connect(self) -> psycopg.Connection:
        return psycopg.connect(
            host=self.settings.database_host,
            port=self.settings.database_port,
            dbname=self.settings.database_name,
            user=self.settings.database_user,
            password=self.settings.database_password,
            row_factory=dict_row,
        )

    def ensure_schema(self) -> None:
        if not self.settings.use_postgres:
            return

        with self._connect() as conn:
            conn.execute(
                """
                create table if not exists app_settings (
                    key text primary key,
                    value text not null,
                    updated_at timestamptz not null default now()
                )
                """
            )
            conn.execute(
                """
                create table if not exists print_batches (
                    id bigint generated by default as identity primary key,
                    timestamp timestamptz not null default now(),
                    "user" text not null,
                    format text not null,
                    warehouse text not null,
                    source text not null default 'inventory',
                    source_document text,
                    source_date date,
                    requested_labels integer not null check (requested_labels > 0),
                    printed_labels integer not null default 0 check (printed_labels >= 0),
                    failed_labels integer not null default 0 check (failed_labels >= 0),
                    status text not null check (status in ('success', 'partial', 'error')),
                    message text
                )
                """
            )
            conn.execute("alter table print_batches add column if not exists source text not null default 'inventory'")
            conn.execute("alter table print_batches add column if not exists source_document text")
            conn.execute("alter table print_batches add column if not exists source_date date")
            conn.execute(
                """
                create table if not exists print_batch_items (
                    id bigint generated by default as identity primary key,
                    batch_id bigint not null references print_batches(id) on delete cascade,
                    product_id bigint,
                    reference text not null,
                    product_description text not null,
                    barcode text not null,
                    presentation text not null,
                    inventory_quantity numeric(14, 4) not null,
                    requested_labels integer not null check (requested_labels > 0),
                    printed_labels integer not null default 0 check (printed_labels >= 0),
                    failed_labels integer not null default 0 check (failed_labels >= 0),
                    status text not null check (status in ('success', 'partial', 'error')),
                    message text
                )
                """
            )
            conn.execute(
                """
                insert into app_settings (key, value)
                values (%s, %s)
                on conflict (key) do nothing
                """,
                (INVENTORY_PRINT_LIMIT_KEY, str(DEFAULT_MAX_LABELS_PER_BATCH)),
            )
            conn.execute(
                "create index if not exists print_batches_timestamp_idx on print_batches (timestamp desc)"
            )
            conn.execute(
                "create index if not exists print_batch_items_batch_id_idx on print_batch_items (batch_id)"
            )

    def get_warehouses(self) -> list[str]:
        self._require_postgres()
        table = sql.Identifier(self.settings.inventory_table)
        with self._connect() as conn:
            rows = conn.execute(
                sql.SQL(
                    "select distinct bodega from {} where bodega <> '' order by bodega"
                ).format(table)
            ).fetchall()
        return [str(row["bodega"]) for row in rows]

    def search_inventory(
        self,
        *,
        warehouse: str,
        search: str | None,
        lines: list[str],
        availability: str,
        limit: int,
        offset: int,
    ) -> tuple[list[InventoryItem], int]:
        self._require_postgres()
        inventory_table = sql.Identifier(self.settings.inventory_table)
        products_table = sql.Identifier(self.settings.products_table)
        pattern = f"%{(search or '').strip()}%"
        selected_lines = [line for line in lines if line]

        query = sql.SQL(
            """
            select inv.id_inventory as id,
                   inv.bodega as warehouse,
                   inv.referencia as reference,
                   inv.inventario as inventory_quantity,
                   min(p.linea) filter (where p.id is not null) as sort_line,
                   min(p.descripcion) filter (where p.id is not null) as sort_description,
                   coalesce(
                       jsonb_agg(
                           jsonb_build_object(
                               'id', p.id,
                               'line', p.linea,
                               'product_code', p.referencia,
                               'description', p.descripcion,
                               'unit_of_measure', p.um_siesa,
                               'barcode', p.codigo_barra,
                               'barcode_unit_measure', p.unidad_de_medida_barras,
                               'quantity_per_unit', p.cantidadxum,
                               'own_code', p.codigo_propio,
                               'presentation_quantity', concat_ws(
                                   ' ',
                                   nullif(p.cantidadxum, ''),
                                   nullif(p.unidad_de_medida_barras, '')
                               )
                           )
                           order by p.codigo_propio desc, p.cantidadxum, p.codigo_barra
                       ) filter (where p.id is not null),
                       '[]'::jsonb
                   ) as presentations
            from {inventory} as inv
            left join {products} as p
              on p.referencia = inv.referencia
             and p.codigo_propio = true
             and (
                 %(line_count)s = 0
                 or p.linea = any(%(lines)s::text[])
             )
            where inv.bodega = %(warehouse)s
              and (
                  %(line_count)s = 0
                  or exists (
                      select 1
                      from {products} as line_product
                      where line_product.referencia = inv.referencia
                        and line_product.codigo_propio = true
                        and line_product.linea = any(%(lines)s::text[])
                  )
              )
              and (
                  %(search)s = ''
                  or inv.referencia ilike %(pattern)s
                  or exists (
                      select 1
                      from {products} as searched_product
                      where searched_product.referencia = inv.referencia
                        and searched_product.codigo_propio = true
                        and (
                            searched_product.descripcion ilike %(pattern)s
                            or searched_product.codigo_barra ilike %(pattern)s
                            or searched_product.linea ilike %(pattern)s
                        )
                  )
              )
            group by inv.id_inventory, inv.bodega, inv.referencia, inv.inventario
            order by sort_line nulls last, sort_description nulls last, inv.referencia
            """
        ).format(inventory=inventory_table, products=products_table)

        with self._connect() as conn:
            rows = conn.execute(
                query,
                {
                    "warehouse": warehouse,
                    "search": (search or "").strip(),
                    "pattern": pattern,
                    "lines": selected_lines,
                    "line_count": len(selected_lines),
                },
            ).fetchall()

        items = [self._inventory_item_from_row(row) for row in rows]
        if availability == "printable":
            items = [item for item in items if item.printable]
        elif availability == "unprintable":
            items = [item for item in items if not item.printable]

        total = len(items)
        return items[offset : offset + limit], total

    def get_settings(self) -> InventoryPrintSettings:
        self._require_postgres()
        with self._connect() as conn:
            row = conn.execute(
                "select value from app_settings where key = %s",
                (INVENTORY_PRINT_LIMIT_KEY,),
            ).fetchone()
        value = int(row["value"]) if row else DEFAULT_MAX_LABELS_PER_BATCH
        return InventoryPrintSettings(max_labels_per_batch=value)

    def get_inventory_selection(
        self,
        *,
        warehouse: str,
        references: list[str],
    ) -> list[InventoryItem]:
        unique_references = set(references)
        items, _ = self.search_inventory(
            warehouse=warehouse,
            search=None,
            lines=[],
            availability="all",
            limit=100_000,
            offset=0,
        )
        return [item for item in items if item.reference in unique_references]

    def search_entry_documents(
        self,
        *,
        warehouse: str,
        search: str | None,
        limit: int,
        offset: int,
    ) -> tuple[list[InventoryEntryDocument], int]:
        self._require_postgres()
        entries_table = sql.Identifier(self.settings.inventory_entries_table)
        pattern = f"%{(search or '').strip()}%"
        query = sql.SQL(
            """
            select max(nullif(proveedor_razon_social, '')) as provider_name,
                   documento as document,
                   bodega as warehouse,
                   max(fecha) as date,
                   count(distinct referencia) as reference_count,
                   coalesce(sum(entradas_inv), 0) as total_entry_quantity
            from {entries}
            where bodega = %(warehouse)s
              and (
                  %(search)s = ''
                  or documento ilike %(pattern)s
                  or referencia ilike %(pattern)s
                  or proveedor_razon_social ilike %(pattern)s
              )
            group by documento, bodega
            order by max(fecha) desc, documento desc
            """
        ).format(entries=entries_table)

        with self._connect() as conn:
            rows = conn.execute(
                query,
                {
                    "warehouse": warehouse,
                    "search": (search or "").strip(),
                    "pattern": pattern,
                },
            ).fetchall()

        total = len(rows)
        documents = [InventoryEntryDocument.model_validate(row) for row in rows]
        return documents[offset : offset + limit], total


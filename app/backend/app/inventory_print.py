    @staticmethod
    def _validate_presentation(product: Product) -> None:
        try:
            quantity = Decimal(product.quantity_per_unit or "")
        except InvalidOperation as exc:
            raise InventoryPrintError("La cantidad por UM no es valida.") from exc
        if quantity <= 0:
            raise InventoryPrintError("La cantidad por UM debe ser positiva.")
        if not product.barcode.strip():
            raise InventoryPrintError("La presentacion no tiene codigo de barras.")

    def _save_batch_history(
        self,
        *,
        user: str,
        format_code: str,
        warehouse: str,
        source: str = "inventory",
        source_document: str | None = None,
        source_date=None,
        requested_labels: int,
        printed_labels: int,
        failed_labels: int,
        status: str,
        message: str | None,
        items: list[InventoryBatchItemResult],
    ) -> int:
        with self._connect() as conn:
            with conn.transaction():
                batch = conn.execute(
                    """
                    insert into print_batches
                        ("user", format, warehouse, source, source_document, source_date,
                         requested_labels, printed_labels, failed_labels, status, message)
                    values (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                    returning id
                    """,
                    (
                        user,
                        format_code,
                        warehouse,
                        source,
                        source_document,
                        source_date,
                        requested_labels,
                        printed_labels,
                        failed_labels,
                        status,
                        message,
                    ),
                ).fetchone()
                batch_id = int(batch["id"])
                with conn.cursor() as cursor:
                    cursor.executemany(
                        """
                        insert into print_batch_items
                            (batch_id, product_id, reference, product_description, barcode,
                             presentation, inventory_quantity, requested_labels,
                             printed_labels, failed_labels, status, message)
                        values (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                        """,
                        [
                            (
                                batch_id,
                                item.product_id,
                                item.reference,
                                item.description,
                                item.barcode,
                                item.presentation,
                                item.inventory_quantity,
                                item.requested_labels,
                                item.printed_labels,
                                item.failed_labels,
                                item.status,
                                item.message,
                            )
                            for item in items
                        ],
                    )
        return batch_id

    def _require_postgres(self) -> None:
        if not self.settings.use_postgres:
            raise InventoryPrintError(
                "La impresion desde inventario requiere CLINIC_DATA_SOURCE=postgres."
            )
